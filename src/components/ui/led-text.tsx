export interface LedTextProps {
  text: string;
  pitchX?: number;
  pitchY?: number;
  dotRadius?: number;
  className?: string;
  color?: string;
  glow?: boolean;
}

/**
 * Reusable, strictly-typed LED Typography component.
 * Pre-computes 7-row bitmap SVG circles on the server with zero layout shift (CLS 0.00).
 */
export function LedText({
  text,
  pitchX = 4,
  pitchY = 4,
  dotRadius = 1.8,
  className = "",
  color = "currentColor",
  glow = false,
}: LedTextProps) {
  const circles: { cx: number; cy: number; key: string }[] = [];
  let currentX = 0;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const glyph = GLYPHS[char] || GLYPHS[char.toLowerCase()] || GLYPHS[" "];
    const colCount = glyph[0]?.length || 3;

    for (let r = 0; r < 7; r++) {
      const rowStr = glyph[r] || "";
      for (let c = 0; c < colCount; c++) {
        if (rowStr[c] === "1") {
          const cx = Math.round((currentX + c * pitchX + 1.55) * 100) / 100;
          const cy = Math.round((r * pitchY + 1.55) * 100) / 100;
          circles.push({ cx, cy, key: `${i}-${r}-${c}` });
        }
      }
    }

    currentX += colCount * pitchX + (char === " " ? 2 : pitchX);
  }

  const totalWidth = Math.max(currentX, 10);
  const totalHeight = 28;

  return (
    <svg
      viewBox={`0 0 ${totalWidth} ${totalHeight}`}
      className={`dot-svg overflow-visible block select-none ${className}`}
      style={{
        width: "auto",
        height: "100%",
        fill: color,
        filter: glow ? "drop-shadow(0 0 4px currentColor)" : "none",
      }}
      aria-label={text}
      role="img"
    >
      {circles.map((dot) => (
        <circle
          key={dot.key}
          cx={dot.cx}
          cy={dot.cy}
          r={dotRadius}
          fill="currentColor"
        />
      ))}
    </svg>
  );
}
